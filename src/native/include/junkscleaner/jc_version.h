#ifndef JUNKS_CLEANER_JC_VERSION_H
#define JUNKS_CLEANER_JC_VERSION_H

#include <stdint.h>

#define JC_ABI_VERSION_MAJOR 1U
#define JC_ABI_VERSION_MINOR 0U
#define JC_ABI_VERSION_PATCH 0U

#define JC_LIBRARY_VERSION_MAJOR 0U
#define JC_LIBRARY_VERSION_MINOR 1U
#define JC_LIBRARY_VERSION_PATCH 0U

#define JC_MAKE_VERSION(major, minor, patch) \
    (((uint32_t)(major) << 24) | ((uint32_t)(minor) << 16) | ((uint32_t)(patch)))

#define JC_CURRENT_ABI_VERSION \
    JC_MAKE_VERSION(JC_ABI_VERSION_MAJOR, JC_ABI_VERSION_MINOR, JC_ABI_VERSION_PATCH)

#define JC_CURRENT_LIBRARY_VERSION \
    JC_MAKE_VERSION(JC_LIBRARY_VERSION_MAJOR, JC_LIBRARY_VERSION_MINOR, JC_LIBRARY_VERSION_PATCH)

#endif /* JUNKS_CLEANER_JC_VERSION_H */
